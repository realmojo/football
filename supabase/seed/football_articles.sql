<p>여기서 &quot;뒤에서 두 번째 상대 선수&quot;는 보통 골키퍼 바로 앞의 마지막 수비수를 말합니다. 골키퍼가 앞으로 나와 있다면 골키퍼가 아니라 수비수 두 명이 기준이 될 수도 있습니다. 또 수비수와 정확히 같은 선에 있으면 오프사이드가 아닙니다. &quot;같은 선이면 공격수에게 유리하게&quot;라는 원칙이 규칙에 그대로 들어가 있는 셈입니다.</p>
<p>위치를 판단할 때는 머리, 몸통, 발처럼 골을 넣을 수 있는 신체 부위만 봅니다. 팔과 손은 겨드랑이 아래 끝까지를 기준으로 판단에서 빠집니다. 골키퍼를 포함한 모든 선수의 팔이 같은 기준을 따릅니다.</p>
<h2>위치만으로는 반칙이 아니다</h2>
<p>오프사이드 위치에 서 있는 것 자체는 반칙이 아닙니다. 동료가 공을 차거나 건드린 순간 오프사이드 위치에 있던 선수가 실제로 플레이에 관여해야 반칙이 됩니다. 규칙이 말하는 관여는 크게 세 가지입니다.</p>
<dl>
<dt>플레이 방해</dt>
<dd>동료가 건넨 공을 직접 받거나 건드리는 경우입니다. 가장 흔한 오프사이드입니다.</dd>
<dt>상대 방해</dt>
<dd>공을 건드리지 않았더라도 골키퍼의 시야를 가리거나, 상대가 공을 처리하려는 움직임을 막거나, 공을 향해 뛰어들어 상대에게 영향을 준 경우입니다. 슈팅 순간 골키퍼 바로 앞에 서 있던 선수 때문에 골이 취소되는 장면이 여기에 해당합니다.</dd>
<dt>이득 취득</dt>
<dd>골대나 상대 선수에게 맞고 튀어나온 공, 또는 상대 골키퍼가 막아낸 공을 오프사이드 위치에 있던 선수가 처리하는 경우입니다.</dd>
</dl>
<p>예외도 있습니다. 골킥, 스로인, 코너킥으로 시작된 공을 바로 받는 경우에는 오프사이드가 적용되지 않습니다. 또 상대 수비수가 일부러 공을 차거나 걷어낸 뒤에는 오프사이드 위치에 있던 선수가 공을 받아도 반칙이 아닙니다. 다만 수비수가 몸에 맞고 튄 공이나 골을 막으려는 &quot;세이브&quot; 동작은 의도적인 플레이로 보지 않습니다.</p>
<p>오프사이드 반칙이 선언되면 상대 팀이 반칙 위치에서 간접 프리킥을 얻습니다. 경고나 퇴장은 따라오지 않습니다.</p>
<h2>VAR은 언제 개입하나</h2>
<p>비디오 판독 심판(VAR)은 2018 러시아 월드컵에서 처음 월드컵 무대에 쓰였고, 지금은 유럽 5대 리그와 챔피언스리그 모두 사용합니다. 중요한 점은 VAR이 모든 판정을 다시 보는 것이 아니라는 점입니다. 경기 규칙은 VAR이 개입할 수 있는 상황을 네 가지로 제한합니다.</p>
<ol>
<li>골 여부 (골 과정의 반칙, 오프사이드, 공이 나갔는지 포함)</li>
<li>페널티킥 여부</li>
<li>곧바로 퇴장을 줄 만한 반칙 (경고 누적 퇴장은 제외)</li>
<li>징계 대상 선수를 잘못 지목한 경우</li>
</ol>
<p>또 VAR은 &quot;명백하고 분명한 오심&quot;이나 &quot;심각하게 놓친 상황&quot;이 있을 때만 주심에게 알립니다. 보는 사람마다 의견이 갈릴 수 있는 애매한 접촉이라면 주심의 원래 판정을 그대로 두는 것이 원칙입니다. 반대로 오프사이드처럼 사실 여부로 판단하는 항목은 화면으로 확인되면 곧바로 판정을 바꿉니다.</p>
<h2>온필드 리뷰와 체크</h2>
<p>VAR은 경기 내내 모든 골과 페널티 판정을 조용히 &quot;체크&quot;합니다. 문제가 없으면 경기는 그대로 이어지고 관중은 확인이 있었는지도 모르고 지나갑니다. 문제가 보이면 두 가지 길이 있습니다.</p>
<ul>
<li><strong>VAR 단독 판정</strong>: 오프사이드 위치, 공이 라인을 넘었는지처럼 사실 확인만 필요한 경우 주심에게 알리고 주심이 판정을 바꿉니다.</li>
<li><strong>온필드 리뷰(OFR)</strong>: 반칙의 강도나 의도처럼 해석이 필요한 경우 주심이 경기장 옆 모니터로 직접 가서 영상을 보고 최종 판단을 내립니다. 최종 결정권은 언제나 주심에게 있습니다.</li>
</ul>
<p>골 장면에서 부심이 깃발을 늦게 드는 것도 VAR 때문입니다. 애매한 오프사이드를 바로 선언해 경기를 끊어 버리면 나중에 골이 맞았다는 게 밝혀져도 되돌릴 수 없기 때문에, 공격이 끝날 때까지 기다렸다가 판정하도록 지침이 바뀌었습니다.</p>
<h2>반자동 오프사이드 기술</h2>
<p>예전에는 VAR 심판이 화면을 멈추고 직접 선을 그어 오프사이드를 판단했습니다. 어느 프레임을 기준으로 하느냐에 따라 결과가 달라질 수 있고 시간도 오래 걸렸습니다. 반자동 오프사이드 기술(SAOT)은 경기장 지붕에 설치한 여러 대의 추적 카메라가 선수들의 신체 부위를 초당 수십 번씩 추적하고, 공 안의 센서나 영상 분석으로 패스 순간을 잡아냅니다.</p>
<p>시스템이 오프사이드 가능성을 알리면 VAR 심판이 확인한 뒤 판정을 내리고, 경기장과 중계 화면에는 3D 그래픽으로 선수 위치가 표시됩니다. 2022 카타르 월드컵에서 본격적으로 쓰인 뒤 챔피언스리그와 여러 유럽 리그로 퍼졌습니다. 판정 시간이 크게 줄었지만, 발끝 몇 센티미터 차이로 골이 취소되는 장면은 여전히 논쟁거리입니다.</p>
